// qx for omp: digests big tool results, at no prompt cost.
//
// omp's native `bash` runs the model's exact command, under omp's own approval (user deny/prompt
// patterns, critical-command prompts, the read-only tier). Nothing here replaces or wraps it. After the
// run, the `tool_result` handler pipes the output through `qx squeeze`, which replaces it with a short
// digest when one fits, and keeps omp's trailing notices (wall time, exit code, truncation) verbatim.
// Every bash result also reaches `qx squeeze` so the command lands in qx history.
//
// Big data-file reads (.json, .log, .csv, ...) are digested through `qx cat`; a ranged or raw read stays
// exact. `session.compacting` adds `qx history --brief` to omp's compaction prompt, so a summary names
// the commands already run. A live savings box below the editor shows `qx gain --line`.
// Every path fails open: on any error or timeout omp keeps the original result.
// Generated by `qx setup omp`; `__QX_EXE__` is replaced with the installed qx path.
import { execFile } from "node:child_process";
import { homedir } from "node:os";
import { isAbsolute, resolve } from "node:path";
import { stat } from "node:fs/promises";

const EXE = "__QX_EXE__";

const REFRESH_MS = 10000;
const ACCENT = "\x1b[36m";
const GREEN = "\x1b[32m";
const DIM = "\x1b[2m";
const RESET = "\x1b[0m";

// Small bordered box around qx's one-line savings summary. Only SGR colour survives omp's
// widget renderer, so the border is plain box-drawing characters.
function renderBox(raw) {
  // The border already carries the `qx` label, so drop the line's own prefix.
  const line = raw.replace(/^qx ▸ /, "");
  const width = [...line].length + 2;
  const body = line.replace(/[−-]?\d+%/g, (m) => `${GREEN}${m}${RESET}`);
  return [
    `${DIM}╭─${RESET} ${ACCENT}qx${RESET} ${DIM}${"─".repeat(Math.max(0, width - 5))}╮${RESET}`,
    `${DIM}│${RESET} ${body} ${DIM}│${RESET}`,
    `${DIM}╰${"─".repeat(width)}╯${RESET}`,
  ];
}

// Runs `EXE args`, resolving to its stdout, or null on any error or timeout. Never rejects.
function run(args, opts, input) {
  return new Promise((done) => {
    try {
      const child = execFile(
        EXE,
        args,
        { windowsHide: true, encoding: "utf8", maxBuffer: 16 * 1024 * 1024, ...opts },
        (err, stdout) => done(err ? null : String(stdout)),
      );
      if (input !== undefined) {
        // A child that exits before reading all of stdin must not raise an unhandled stream error.
        child.stdin?.on("error", () => {});
        child.stdin?.end(input);
      }
    } catch {
      done(null);
    }
  });
}

// Data files whose big `read` results qx digests. The extension must end the path, so a selector
// suffix (`:N`, `:N-M`, `:raw`, `:+N`, `:-N`) never matches: a ranged or raw read is deliberate.
const DATA_FILE = /\.(json|jsonl|ndjson|log|csv|tsv)$/i;
const DATA_MIN_CHARS = 6000;

function textOf(content) {
  if (!Array.isArray(content)) return null;
  let text = "";
  for (const part of content) {
    if (!part || part.type !== "text" || typeof part.text !== "string") return null;
    text += part.text;
  }
  return text;
}

// The digest replacing a big data-file read result, or undefined to keep the original.
async function digestRead(event, ctx) {
  if (event?.toolName !== "read" || event.isError) return undefined;
  const path = event.input?.path;
  if (typeof path !== "string" || !DATA_FILE.test(path)) return undefined;
  const original = textOf(event.content);
  if (original === null || original.length <= DATA_MIN_CHARS) return undefined;
  const cwd = ctx?.cwd || process.cwd();
  const home = path === "~" || /^~[\\/]/.test(path) ? homedir() + path.slice(1) : path;
  const abs = isAbsolute(home) ? home : resolve(cwd, home);
  // Only a regular file goes to `qx cat`: a missing file, URL or internal URI must not spawn.
  try {
    if (!(await stat(abs)).isFile()) return undefined;
  } catch {
    return undefined;
  }
  const stdout = await run(["cat", abs], { timeout: 3000, cwd });
  const digest = stdout?.trim();
  if (!digest || digest.length >= original.length * 0.7) return undefined;
  const footer = `[qx] digest of ${path}; read ${path} with a line range (${path}:N-M) for exact text`;
  return { content: [{ type: "text", text: `${digest}\n${footer}` }] };
}

const EXIT_NOTICE = /^Command exited with code (-?\d+)$/;
const NOTICE_LINES = [
  /^Wall time: .* seconds$/,
  EXIT_NOTICE,
  /^\[.*\]$/,
  // omp's fork notices (tools/bash.ts).
  /^Ran in a copy of the busy session shell; changes here won't persist\.$/,
  /^Background jobs started here run in a copy of the busy session shell; later calls' jobs, wait and %N won't see them\.$/,
];

// Splits omp's trailing notices off a bash result: `trailer` is the blank and notice lines at the
// end, verbatim (leading newline included), `body` the command output before them.
function splitTrailer(text) {
  const lines = text.split("\n");
  let end = lines.length;
  while (end > 0) {
    const line = lines[end - 1].trimEnd();
    if (line !== "" && !NOTICE_LINES.some((re) => re.test(line))) break;
    end--;
  }
  const body = lines.slice(0, end).join("\n");
  return { body, trailer: text.slice(body.length) };
}

// The command's exit code: omp's details on a failed exit, else its notice, else 124 on a timeout.
function exitCodeOf(event, trailer) {
  const code = event.details?.exitCode;
  if (typeof code === "number") return code;
  for (const line of trailer.split("\n")) {
    const m = EXIT_NOTICE.exec(line.trimEnd());
    if (m) return Number(m[1]);
  }
  return event.details?.timedOut ? 124 : 0;
}

// The digest replacing a bash result, or undefined to keep the original. Also records the command in
// qx history, so it runs for every result with output.
async function squeezeBash(event, ctx) {
  if (event?.toolName !== "bash") return undefined;
  const command = event.input?.command;
  if (typeof command !== "string" || !command) return undefined;
  const text = textOf(event.content);
  if (text === null) return undefined;
  const { body, trailer } = splitTrailer(text);
  if (!body.trim()) return undefined;
  const base = ctx?.cwd || process.cwd();
  const cwd = typeof event.input.cwd === "string" && event.input.cwd ? resolve(base, event.input.cwd) : base;
  const stdout = await run(
    ["squeeze", "--label", command, "--code", String(exitCodeOf(event, trailer)), "--cwd", cwd, "--max-ratio", "70"],
    { timeout: 5000 },
    body,
  );
  const out = stdout?.trimEnd();
  if (!out || out.length >= body.length) return undefined;
  return { content: [{ type: "text", text: out + trailer }] };
}

const HISTORY_HEADER = "Commands already run in this repo (from qx history; re-run only if files changed):";

// Lines for omp's compaction prompt, or undefined when qx has nothing. Bounded by the 2 s timeout.
async function compactionContext(ctx) {
  const stdout = await run(["history", "--brief"], { timeout: 2000, cwd: ctx?.cwd || process.cwd() });
  const lines = (stdout ?? "").split(/\r?\n/).filter((l) => l.trim());
  return lines.length ? { context: [HISTORY_HEADER, ...lines] } : undefined;
}

export default function (pi) {
  // Stops this session's refresh timer. Subagents re-run this factory and fire session_start, so the
  // variable lives here: a module-level one would let a child clear the parent's timer.
  let stopRefresh = () => {};

  // Live savings box below the editor, refreshed on a crash-isolated timer. session_start fires
  // again for new/resumed sessions, so the previous timer is cleared first or intervals stack.
  // Without ctx.ui (print / non-interactive mode) there is nothing to draw on.
  pi.on("session_start", (_event, ctx) => {
    stopRefresh();
    if (!ctx?.ui?.setWidget || !ctx.setInterval) return;
    let stopped = false;
    const refresh = () => {
      execFile(EXE, ["gain", "--line"], { timeout: 2000, windowsHide: true, encoding: "utf8" }, (err, stdout) => {
        if (stopped) return;
        try {
          const text = err ? "" : String(stdout).trim();
          // No dedupe: re-setting every tick redraws a widget the host dropped. On failure or empty
          // output the widget is cleared rather than left showing stale numbers.
          ctx.ui.setWidget("qx", text ? renderBox(text) : undefined, { placement: "belowEditor" });
        } catch {
          // A widget must never break its host.
        }
      });
    };
    refresh();
    const timer = ctx.setInterval(refresh, REFRESH_MS);
    stopRefresh = () => {
      stopped = true;
      try {
        ctx.clearTimer?.(timer);
      } catch {
        // The host may already have cleared it.
      }
      stopRefresh = () => {};
    };
  });

  pi.on("session_shutdown", () => {
    stopRefresh();
  });

  pi.on("tool_result", async (event, ctx) => {
    try {
      return (await squeezeBash(event, ctx)) ?? (await digestRead(event, ctx));
    } catch {
      return undefined;
    }
  });

  // qx never rewrites old messages; it only adds its command history to the compaction prompt.
  pi.on("session.compacting", async (_event, ctx) => {
    try {
      return await compactionContext(ctx);
    } catch {
      return undefined;
    }
  });
}
